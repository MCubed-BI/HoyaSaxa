import { getSql } from "@/lib/db";
import { ensureBlastTables } from "@/lib/blast-schema";

let ensured = false;

/** CRM notes / donation calls + push blast tables (SMS/email live in blast-schema). */
export async function ensureCrmTables() {
  if (ensured) return;
  const sql = getSql();
  await ensureBlastTables();

  await sql.query(`
    CREATE TABLE IF NOT EXISTS alumni_crm_notes (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      alumni_id uuid NOT NULL REFERENCES alumni(id) ON DELETE CASCADE,
      kind text NOT NULL DEFAULT 'note',
      body text NOT NULL DEFAULT '',
      called_at timestamptz,
      created_by text,
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await sql.query(`
    DO $$
    BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'alumni_crm_notes_kind_check'
      ) THEN
        ALTER TABLE alumni_crm_notes
          ADD CONSTRAINT alumni_crm_notes_kind_check
          CHECK (kind IN ('note', 'donation_call'));
      END IF;
    END $$;
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS idx_alumni_crm_notes_alumni
    ON alumni_crm_notes (alumni_id, created_at DESC)
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS idx_alumni_crm_notes_donation_calls
    ON alumni_crm_notes (alumni_id, called_at DESC)
    WHERE kind = 'donation_call'
  `);

  await sql.query(`
    CREATE TABLE IF NOT EXISTS push_blasts (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      title text,
      body text NOT NULL,
      status text NOT NULL DEFAULT 'draft',
      provider text,
      recipient_count integer NOT NULL DEFAULT 0,
      sent_count integer NOT NULL DEFAULT 0,
      failed_count integer NOT NULL DEFAULT 0,
      filter_snapshot jsonb NOT NULL DEFAULT '{}'::jsonb,
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await sql.query(`
    CREATE TABLE IF NOT EXISTS push_blast_recipients (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      blast_id uuid NOT NULL REFERENCES push_blasts(id) ON DELETE CASCADE,
      alumni_id uuid REFERENCES alumni(id) ON DELETE SET NULL,
      name text,
      device_token text,
      status text NOT NULL DEFAULT 'pending',
      error text,
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS idx_push_blast_recipients_alumni
    ON push_blast_recipients (alumni_id, created_at DESC)
    WHERE alumni_id IS NOT NULL
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS idx_text_blast_recipients_alumni
    ON text_blast_recipients (alumni_id, created_at DESC)
    WHERE alumni_id IS NOT NULL
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS idx_email_blast_recipients_alumni
    ON email_blast_recipients (alumni_id, created_at DESC)
    WHERE alumni_id IS NOT NULL
  `);

  ensured = true;
}

export function resetCrmTablesCache() {
  ensured = false;
}
