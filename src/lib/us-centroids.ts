export function normalizeState(value: string | null | undefined): string | null {
  if (!value) return null;
  const cleaned = value.replace(/\./g, "").trim();
  if (!cleaned) return null;
  const upper = cleaned.toUpperCase();
  if (US_STATE_CENTROIDS[upper]) return upper;
  const named = STATE_NAMES[cleaned.toLowerCase()];
  return named ?? null;
}

export function normalizeCity(value: string | null | undefined): string | null {
  if (!value) return null;
  const cleaned = value
    .replace(/\./g, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
  return cleaned || null;
}

export function cityStateKey(city: string | null | undefined, state: string | null | undefined): string | null {
  const cityKey = normalizeCity(city);
  const stateKey = normalizeState(state);
  if (!cityKey || !stateKey) return null;
  return `${cityKey}|${stateKey}`;
}
