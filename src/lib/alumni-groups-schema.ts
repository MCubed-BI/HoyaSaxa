import { getSql } from "@/lib/db";

let ensured = false;

export async function ensureAlumniGroupsTables() {
  if (ensured) return;
  const sql = getSql();
  await sql.query(`
    CREATE TABLE IF NOT EXISTS alumni_groups (
      id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
      name text NOT NULL,
      description text,
      created_by text,
      created_at timestamptz NOT NULL DEFAULT now(),
      updated_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await sql.query(`
    CREATE TABLE IF NOT EXISTS alumni_group_members (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      group_id uuid NOT NULL REFERENCES alumni_groups(id) ON DELETE CASCADE,
      alumni_id uuid NOT NULL REFERENCES alumni(id) ON DELETE CASCADE,
      created_at timestamptz NOT NULL DEFAULT now(),
      UNIQUE (group_id, alumni_id)
    )
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS alumni_group_members_alumni_id_idx
      ON alumni_group_members (alumni_id)
  `);
  await sql.query(`
    CREATE INDEX IF NOT EXISTS alumni_groups_name_lower_idx
      ON alumni_groups (lower(name))
  `);
  ensured = true;
}

/** Test helper — allow re-running ensure after schema drops in tests. */
export function resetAlumniGroupsEnsureFlag() {
  ensured = false;
}
